#!/usr/bin/env python3
"""Generate the bitmap fonts for the T-Dongle-S3 display into main/lcd_font.c.

    scripts/gen-lcd-font.py [--preview out.png]

Source: the X11 "misc-fixed" character-cell fonts 9x18B (large) and 7x13B
(small), Unicode (ISO 10646) builds as shipped in Debian/Ubuntu's
xfonts-base package (/usr/share/fonts/X11/misc/*.pcf.gz, font-misc-misc).
Their licence is "Public domain font.  Share and enjoy." (see
/usr/share/doc/xfonts-base/copyright), so the bitmaps can be embedded.

Covered code points, in glyph-index order (display_model.c's
dm_glyph_index() mirrors this layout):
  0..94    U+0020..U+007E   printable ASCII
  95..190  U+00A0..U+00FF   Latin-1 supplement (äöüÄÖÜß, Western accents)
  191..    EXTRA_CPS below  ellipsis for truncation, plus the CP1252 letters
                            Latin-1 lacks (Œœ Šš Žž Ÿ €)

Each glyph is the full w x h cell, rows top to bottom, packed MSB first as
one continuous bit stream and padded to whole bytes, so glyph i starts at
bits[i * bytes_per_glyph]. The generated file is committed: the firmware
build needs neither the fonts nor Pillow.

Needs: Pillow, xfonts-base.
"""

import argparse
import gzip
import io
import os
import sys

from PIL import Image, PcfFontFile

FIRMWARE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(FIRMWARE, "main/lcd_font.c")
FONT_DIR = "/usr/share/fonts/X11/misc"

# (C name, PCF file)
FONTS = [("lcd_font_large", "9x18B.pcf.gz"),
         ("lcd_font_small", "7x13B.pcf.gz")]

EXTRA_CPS = [0x2026,                    # … (truncation marker)
             0x20AC,                    # €
             0x0152, 0x0153,            # Œ œ
             0x0160, 0x0161,            # Š š
             0x017D, 0x017E,            # Ž ž
             0x0178]                    # Ÿ

CODE_POINTS = list(range(0x20, 0x7F)) + list(range(0xA0, 0x100)) + EXTRA_CPS


class UnicodePcf(PcfFontFile.PcfFontFile):
    """PcfFontFile maps at most 256 byte codes through a charset; this
    subclass maps glyph slot i to CODE_POINTS[i] in a Unicode PCF instead."""

    def _load_encoding(self):
        fp, _format, i16, _i32 = self._getformat(PcfFontFile.PCF_BDF_ENCODINGS)
        first_col, last_col = i16(fp.read(2)), i16(fp.read(2))
        first_row, last_row = i16(fp.read(2)), i16(fp.read(2))
        i16(fp.read(2))  # default char
        cols = last_col - first_col + 1
        n = cols * (last_row - first_row + 1)
        offsets = [i16(fp.read(2)) for _ in range(n)]
        encoding = []
        for cp in CODE_POINTS:
            row, col = cp >> 8, cp & 0xFF
            if not (first_row <= row <= last_row and first_col <= col <= last_col):
                raise SystemExit("U+%04X not in font" % cp)
            off = offsets[(row - first_row) * cols + (col - first_col)]
            if off == 0xFFFF:
                raise SystemExit("U+%04X not in font" % cp)
            encoding.append(off)
        return encoding


def load(filename):
    with gzip.open(os.path.join(FONT_DIR, filename)) as f:
        font = UnicodePcf(io.BytesIO(f.read()))
    cells = []
    width = height = None
    for i in range(len(CODE_POINTS)):
        glyph = font.glyph[i]
        image = glyph[3]
        if width is None:
            width, height = image.size
        elif image.size != (width, height):
            raise SystemExit("%s: not a character-cell font" % filename)
        cells.append(image)
    return width, height, cells


def pack(image, width, height):
    bits = []
    for y in range(height):
        for x in range(width):
            bits.append(1 if image.getpixel((x, y)) else 0)
    while len(bits) % 8:
        bits.append(0)
    return bytes(int("".join(map(str, bits[i:i + 8])), 2) for i in range(0, len(bits), 8))


def write(fonts):
    with open(OUT, "w") as out:
        out.write("// Generated by scripts/gen-lcd-font.py — do not edit.\n")
        out.write("// X11 misc-fixed fonts (xfonts-base), public domain.\n\n")
        out.write('#include "lcd_font.h"\n\n')
        out.write("const uint16_t lcd_font_extra_cps[LCD_FONT_EXTRA_GLYPHS] = {\n    ")
        out.write(", ".join("0x%04x" % cp for cp in EXTRA_CPS))
        out.write(",\n};\n")
        total = 0
        for name, (width, height, cells) in fonts:
            per = (width * height + 7) // 8
            data = b"".join(pack(c, width, height) for c in cells)
            total += len(data)
            out.write("\nstatic const uint8_t %s_bits[%d] = {\n" % (name, len(data)))
            for i in range(0, len(data), per):
                cp = CODE_POINTS[i // per]
                chunk = ", ".join("0x%02x" % b for b in data[i:i + per])
                out.write("    %s, // U+%04X\n" % (chunk, cp))
            out.write("};\n\n")
            out.write("const lcd_font_t %s = {\n" % name)
            out.write("    .w = %d, .h = %d, .bytes_per_glyph = %d, .bits = %s_bits,\n"
                      % (width, height, per, name))
            out.write("};\n")
    return total


def preview(fonts, path):
    rows = []
    for _name, (width, height, cells) in fonts:
        per_row = 32
        lines = (len(cells) + per_row - 1) // per_row
        image = Image.new("1", (per_row * width, lines * height), 0)
        for i, cell in enumerate(cells):
            image.paste(cell, ((i % per_row) * width, (i // per_row) * height))
        rows.append(image)
    out = Image.new("1", (max(r.size[0] for r in rows), sum(r.size[1] + 4 for r in rows)), 0)
    y = 0
    for r in rows:
        out.paste(r, (0, y))
        y += r.size[1] + 4
    out.save(path)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--preview", help="also save all glyphs as PNG")
    args = parser.parse_args()
    if len(CODE_POINTS) - 191 != len(EXTRA_CPS):
        raise SystemExit("glyph layout changed; update dm_glyph_index()")
    fonts = [(name, load(filename)) for name, filename in FONTS]
    if args.preview:
        preview(fonts, args.preview)
    total = write(fonts)
    print("%s: %d glyphs per font, %d bytes of bitmaps" % (OUT, len(CODE_POINTS), total),
          file=sys.stderr)


if __name__ == "__main__":
    main()
