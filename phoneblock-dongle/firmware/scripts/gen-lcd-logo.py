#!/usr/bin/env python3
"""Render the boot logo for the T-Dongle-S3 display into main/lcd_logo.c.

    scripts/gen-lcd-logo.py [--preview out.png]

The logo is phoneblock/src/main/webapp/assets/img/app-logo.svg next to the
word mark, 160x80 landscape. Output is RGB565 run-length encoded as
(count, colour) pairs, colour already byte-swapped into the order the panel
reads over SPI, so display.c only expands runs. The generated file is
committed: the firmware build needs neither Inkscape nor Pillow.

Needs: inkscape, Pillow, the Noto Sans Bold font.
"""

import argparse
import os
import subprocess
import sys
import tempfile

from PIL import Image, ImageDraw, ImageFont

FIRMWARE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REPO = os.path.dirname(os.path.dirname(FIRMWARE))
SVG = os.path.join(REPO, "phoneblock/src/main/webapp/assets/img/app-logo.svg")
OUT = os.path.join(FIRMWARE, "main/lcd_logo.c")
FONT = "/usr/share/fonts/truetype/noto/NotoSans-Bold.ttf"

W, H = 160, 80
BACKGROUND = (16, 24, 40)
LOGO = 72


def render():
    with tempfile.TemporaryDirectory() as tmp:
        png = os.path.join(tmp, "logo.png")
        subprocess.run(["inkscape", SVG, "--export-type=png",
                        "--export-filename=" + png, "-w", str(LOGO)],
                       check=True, stdout=subprocess.DEVNULL,
                       stderr=subprocess.DEVNULL)
        logo = Image.open(png).convert("RGBA")
        logo.load()

    image = Image.new("RGB", (W, H), BACKGROUND)
    draw = ImageDraw.Draw(image)
    top = (H - LOGO) // 2
    # White disc behind the sign: the black handset would vanish on the
    # dark background otherwise. Inset well inside the red ring, so the
    # ring's anti-aliased outer edge blends into the background, not into
    # white (that showed as a white halo on the panel).
    inset = 6
    draw.ellipse((top + inset, top + inset, top + LOGO - inset, top + LOGO - inset),
                 fill=(255, 255, 255))
    image.paste(logo, (top, top), logo)
    font = ImageFont.truetype(FONT, 22)
    draw.text((top + LOGO + 6, 10), "Phone", font=font, fill=(255, 255, 255))
    draw.text((top + LOGO + 6, 40), "Block", font=font, fill=(230, 40, 40))
    return image


def rgb565_swapped(rgb):
    r, g, b = rgb
    value = ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)
    return ((value & 0xFF) << 8) | (value >> 8)


def runs(image):
    result = []
    for pixel in image.getdata():
        colour = rgb565_swapped(pixel)
        if result and result[-1][1] == colour and result[-1][0] < 0xFFFF:
            result[-1][0] += 1
        else:
            result.append([1, colour])
    return result


def write(rle):
    words = [v for pair in rle for v in pair]
    lines = []
    for i in range(0, len(words), 12):
        lines.append("    " + ", ".join("0x%04x" % w for w in words[i:i + 12]) + ",")
    with open(OUT, "w") as out:
        out.write("// Generated by scripts/gen-lcd-logo.py — do not edit.\n")
        out.write("// %dx%d RGB565, %d runs of (count, colour).\n\n" % (W, H, len(rle)))
        out.write('#include "lcd_logo.h"\n\n')
        out.write("const uint16_t lcd_logo_rle[] = {\n")
        out.write("\n".join(lines) + "\n};\n\n")
        out.write("const size_t lcd_logo_rle_len = sizeof(lcd_logo_rle) / sizeof(lcd_logo_rle[0]);\n")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--preview", help="also save the image as PNG")
    args = parser.parse_args()
    image = render()
    if args.preview:
        image.save(args.preview)
    rle = runs(image)
    write(rle)
    print("%s: %d runs, %d bytes" % (OUT, len(rle), len(rle) * 4), file=sys.stderr)


if __name__ == "__main__":
    main()
