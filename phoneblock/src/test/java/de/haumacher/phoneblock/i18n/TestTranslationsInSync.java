package de.haumacher.phoneblock.i18n;

import static org.junit.jupiter.api.Assertions.*;

import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.Charset;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.Properties;
import java.util.Set;
import java.util.TreeMap;
import java.util.TreeSet;
import java.util.stream.Collectors;
import java.util.stream.Stream;

import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.condition.EnabledIfEnvironmentVariable;
import org.w3c.dom.Document;

import de.haumacher.autotranslate.html.extract.HtmlAnalyzer;
import de.haumacher.autotranslate.html.extract.PropertiesExtractor;

/**
 * Checks that all generated translations match the German sources.
 *
 * <p>
 * German is the only source language. All other locales are generated by DeepL-backed plugins
 * that only run in the opt-in {@code with-deepl} profile. When a German change is committed
 * without the generated files, every later DeepL build regenerates them and dirties every
 * checkout. This test catches that in CI.
 * </p>
 *
 * <p>
 * The {@code data-tx} checksums are computed with the {@link HtmlAnalyzer} of the
 * auto-translate library, the same code the auto-translate-maven-plugin uses.
 * </p>
 *
 * <p>
 * Runs only in CI (GitHub Actions sets {@code CI=true}), so that a developer without DeepL
 * access is never blocked locally. Run it locally with {@code CI=true mvn -pl phoneblock test
 * -Dtest=TestTranslationsInSync} (add {@code -P '!with-deepl'} if that profile is active in
 * your settings, otherwise the build regenerates the translations before the check).
 * </p>
 */
@EnabledIfEnvironmentVariable(named = "CI", matches = "true")
public class TestTranslationsInSync {

	private static final String SOURCE_LANG = "de";

	private static final Path MESSAGES_DIR = Path.of("src/main/java");

	private static final Path WEB_TEMPLATES = Path.of("src/main/webapp/WEB-INF/templates");

	private static final Path MAIL_TEMPLATES = Path.of("src/main/java/de/haumacher/phoneblock/mail/templates");

	private static final String HINT = "German source changed without regenerated translations"
		+ " — run the build with -Pwith-deepl (see CLAUDE.md) and commit the generated files.";

	private static final String MESSAGES_HINT = "German source changed without regenerated translations"
		+ " — run the build with -Pwith-deepl (see CLAUDE.md, \"Server Messages Internationalization\")"
		+ " and commit all generated Messages_*.properties files.";

	/**
	 * Every {@code Messages_<lang>.properties} has exactly the keys of
	 * {@code Messages_de.properties}.
	 */
	@Test
	void messageBundlesHaveGermanKeys() throws IOException {
		Path sourceFile = MESSAGES_DIR.resolve("Messages_" + SOURCE_LANG + ".properties");
		Set<String> sourceKeys = keys(sourceFile);

		List<Path> bundles;
		try (Stream<Path> files = Files.list(MESSAGES_DIR)) {
			bundles = files
				.filter(f -> f.getFileName().toString().matches("Messages_.+\\.properties"))
				.filter(f -> !f.equals(sourceFile))
				.sorted()
				.toList();
		}
		assertFalse(bundles.isEmpty(), "No translated message bundles found in " + MESSAGES_DIR);

		List<String> problems = new ArrayList<>();
		for (Path bundle : bundles) {
			Set<String> keys = keys(bundle);

			Set<String> missing = new TreeSet<>(sourceKeys);
			missing.removeAll(keys);
			Set<String> extra = new TreeSet<>(keys);
			extra.removeAll(sourceKeys);

			if (!missing.isEmpty()) {
				problems.add(bundle + ": missing keys " + missing);
			}
			if (!extra.isEmpty()) {
				problems.add(bundle + ": keys not in " + sourceFile.getFileName() + " " + extra);
			}
		}

		assertNoProblems(problems, MESSAGES_HINT);
	}

	/**
	 * Every German web template has up-to-date {@code data-tx} checksums.
	 */
	@Test
	void webTemplatesHaveCurrentChecksums() throws Exception {
		checkSourceChecksums(WEB_TEMPLATES);
	}

	/**
	 * Every German mail template has up-to-date {@code data-tx} checksums.
	 */
	@Test
	void mailTemplatesHaveCurrentChecksums() throws Exception {
		checkSourceChecksums(MAIL_TEMPLATES);
	}

	/**
	 * Every locale has each German web template, translated from its current text.
	 */
	@Test
	void webTemplateTranslationsMatchGerman() throws Exception {
		checkTranslations(WEB_TEMPLATES);
	}

	/**
	 * Every locale has each German mail template, translated from its current text.
	 */
	@Test
	void mailTemplateTranslationsMatchGerman() throws Exception {
		checkTranslations(MAIL_TEMPLATES);
	}

	/**
	 * Compares the checksums stored in the {@code data-tx} attributes of the German templates with
	 * the checksums of their current text, as the plugin computes them. A difference is a German
	 * text that was changed (or added) without running the translation.
	 */
	private static void checkSourceChecksums(Path templateDir) throws Exception {
		assertUtf8();

		List<String> problems = new ArrayList<>();
		for (Path file : sourceTemplates(templateDir)) {
			// Not extract-only: assigns IDs to new texts and computes the current checksums,
			// exactly as the plugin does before translating. Only the in-memory DOM is changed.
			HtmlAnalyzer analyzer = new HtmlAnalyzer(PropertiesExtractor.parseHtml(file.toFile()));
			analyzer.analyze();

			Map<String, String> currentCrcs = analyzer.getCrcById();
			Map<String, String> storedCrcs = analyzer.getOldCrcById();
			Set<String> existingIds = analyzer.getExistingIds();
			Map<String, String> texts = analyzer.getTextById();

			for (String id : new TreeSet<>(currentCrcs.keySet())) {
				String currentCrc = currentCrcs.get(id);
				if (!existingIds.contains(id)) {
					problems.add(file + ": text without data-tx (new text, would get " + id + ")" + text(texts, id));
				} else {
					String storedCrc = storedCrcs.get(id);
					if (storedCrc == null) {
						problems.add(file + ": data-tx=\"" + id + "\" has no checksum, expected \"" + id + ":"
							+ currentCrc + "\"" + text(texts, id));
					} else if (!storedCrc.equals(currentCrc)) {
						problems.add(file + ": data-tx=\"" + id + ":" + storedCrc + "\" does not match the German text"
							+ " (current checksum " + currentCrc + ")" + text(texts, id));
					}
				}
			}
		}

		assertNoProblems(problems, HINT);
	}

	/**
	 * Checks that each locale directory has every German template with the same {@code data-tx}
	 * IDs and checksums, i.e. that it was translated from the current German text.
	 */
	private static void checkTranslations(Path templateDir) throws Exception {
		Path sourceDir = templateDir.resolve(SOURCE_LANG);
		List<Path> sources = sourceTemplates(templateDir);

		List<Path> localeDirs;
		try (Stream<Path> dirs = Files.list(templateDir)) {
			localeDirs = dirs
				.filter(Files::isDirectory)
				.filter(d -> !d.getFileName().toString().equals(SOURCE_LANG))
				.sorted()
				.toList();
		}
		assertFalse(localeDirs.isEmpty(), "No locale directories found in " + templateDir);

		// The checksums recorded in the German data-tx attributes. Whether they match the German
		// text is checked separately in checkSourceChecksums().
		Map<Path, Map<String, String>> sourceCrcs = new TreeMap<>();
		for (Path source : sources) {
			sourceCrcs.put(sourceDir.relativize(source), storedCrcs(source));
		}

		List<String> problems = new ArrayList<>();
		for (Path localeDir : localeDirs) {
			for (Map.Entry<Path, Map<String, String>> entry : sourceCrcs.entrySet()) {
				Path relative = entry.getKey();
				Path target = localeDir.resolve(relative.toString());
				if (!Files.isRegularFile(target)) {
					problems.add(target + ": missing (translation of " + sourceDir.resolve(relative) + ")");
					continue;
				}

				Map<String, String> expected = entry.getValue();
				Map<String, String> actual = storedCrcs(target);

				Set<String> missing = new TreeSet<>(expected.keySet());
				missing.removeAll(actual.keySet());
				if (!missing.isEmpty()) {
					problems.add(target + ": missing data-tx units " + missing);
				}

				Set<String> extra = new TreeSet<>(actual.keySet());
				extra.removeAll(expected.keySet());
				if (!extra.isEmpty()) {
					problems.add(target + ": data-tx units not in the German template " + extra);
				}

				for (String id : new TreeSet<>(expected.keySet())) {
					String expectedCrc = expected.get(id);
					String actualCrc = actual.get(id);
					if (actualCrc != null && !actualCrc.equals(expectedCrc)) {
						problems.add(target + ": data-tx=\"" + id + ":" + actualCrc
							+ "\" is translated from an outdated German text (German: \"" + id + ":" + expectedCrc + "\")");
					}
				}
			}

			Set<Path> orphans = new TreeSet<>();
			for (Path target : htmlFiles(localeDir)) {
				Path relative = localeDir.relativize(target);
				if (!sourceCrcs.containsKey(Path.of(relative.toString()))) {
					orphans.add(target);
				}
			}
			for (Path orphan : orphans) {
				problems.add(orphan + ": no German source " + sourceDir.resolve(localeDir.relativize(orphan).toString())
					+ " (delete the translation together with the German template)");
			}
		}

		assertNoProblems(problems, HINT);
	}

	/**
	 * The {@code data-tx} IDs of the given template with the checksums recorded in it ({@code null}
	 * for an ID without checksum).
	 */
	private static Map<String, String> storedCrcs(Path file) throws Exception {
		Document document = PropertiesExtractor.parseHtml(file.toFile());
		HtmlAnalyzer analyzer = new HtmlAnalyzer(document).setExtractOnly(true);
		analyzer.analyze();

		Map<String, String> result = new TreeMap<>();
		for (String id : analyzer.getExistingIds()) {
			result.put(id, analyzer.getOldCrcById().get(id));
		}
		return result;
	}

	private static List<Path> sourceTemplates(Path templateDir) throws IOException {
		Path sourceDir = templateDir.resolve(SOURCE_LANG);
		assertTrue(Files.isDirectory(sourceDir), "Source directory missing: " + sourceDir.toAbsolutePath());
		List<Path> result = htmlFiles(sourceDir);
		assertFalse(result.isEmpty(), "No templates found in " + sourceDir);
		return result;
	}

	private static List<Path> htmlFiles(Path dir) throws IOException {
		try (Stream<Path> files = Files.walk(dir)) {
			return files
				.filter(Files::isRegularFile)
				.filter(f -> f.getFileName().toString().endsWith(".html"))
				.sorted()
				.toList();
		}
	}

	private static Set<String> keys(Path file) throws IOException {
		// Only the keys are compared, which are ASCII. The generated bundles are not all UTF-8.
		Properties properties = new Properties();
		try (InputStream in = Files.newInputStream(file)) {
			properties.load(in);
		}
		return properties.stringPropertyNames().stream().collect(Collectors.toCollection(TreeSet::new));
	}

	private static String text(Map<String, String> texts, String id) {
		String text = texts.get(id);
		if (text == null) {
			// Only attribute texts (e.g. title, placeholder) for this element.
			text = texts.entrySet().stream()
				.filter(e -> e.getKey().startsWith(id + "."))
				.map(e -> e.getKey().substring(id.length() + 1) + "=" + e.getValue())
				.collect(Collectors.joining(", "));
		}
		text = text.strip().replaceAll("\\s+", " ");
		if (text.length() > 120) {
			text = text.substring(0, 117) + "...";
		}
		return ": \"" + text + "\"";
	}

	/**
	 * The plugin computes the checksums over {@link String#getBytes()}, i.e. with the platform
	 * charset. The committed checksums were computed with UTF-8.
	 */
	private static void assertUtf8() {
		assertEquals(StandardCharsets.UTF_8, Charset.defaultCharset(),
			"The data-tx checksums are computed with the default charset, which must be UTF-8"
				+ " (run with a UTF-8 locale or -Dfile.encoding=UTF-8).");
	}

	private static void assertNoProblems(List<String> problems, String hint) {
		if (!problems.isEmpty()) {
			fail(hint + "\n  " + String.join("\n  ", problems) + "\n" + problems.size() + " problem(s). " + hint);
		}
	}
}
